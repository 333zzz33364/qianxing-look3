const indexMap = studio => {
  const out = {}
  walk(studio.get().root, node => { if (node.kind !== 'server-container') out[node.name] = node.giaInfoIndex })
  return out
}

test('new nested assets retain creation-order indices even when tree order differs', () => {
  const studio = createStudio(emptyAuthoring())
  studio.patch({ op: 'addTemplate', kind: 'container', name: 'Empty' })
  const tree = studio.patch({ op: 'addTemplate', kind: 'container', name: 'Tree' }).selectedId
  studio.patch({ op: 'add', kind: 'cursor', parentId: tree, name: 'CursorA' })
  studio.patch({ op: 'add', kind: 'textbox', parentId: tree, name: 'TextA' })
  const imageB = studio.patch({ op: 'add', kind: 'image', parentId: tree, name: 'ImageB' }).selectedId
  studio.patch({ op: 'add', kind: 'image', parentId: tree, name: 'ImageA' })
  studio.patch({ op: 'add', kind: 'image', parentId: imageB, name: 'DeepImage' })
  const observed = { Empty: 2, Tree: 3, CursorA: 4, TextA: 5, ImageB: 6, ImageA: 7, DeepImage: 8 }
  assert.deepEqual(indexMap(studio), observed)
  for (const format of ['gia', 'gia-combined']) {
    const buffer = encodeStudio(studio, format)
    const indices = byName(buffer)
    for (const [name, index] of Object.entries(observed)) assert.equal(indices[name], index, `${format}.${name}`)
    const images = readIndices(buffer).filter(row => ['ImageB', 'ImageA', 'DeepImage'].includes(row.name))
    assert.deepEqual(images.map(row => row.index), [7, 6, 8], 'native bottom-first DFS must retain the original asset registration numbers')
  }
})

test('asset numbers persist through reorder, reparent, JSON reload and deletion', () => {
  let studio = createStudio(importGia(nativeLayers()).project)
  const expected = indexMap(studio)
  const tree = studio.get().root.children[1].id
  const imageA = studio.get().tree.find(row => row.name === 'ImageA').id
  studio.patch({ op: 'moveSibling', id: imageA, direction: 'up' })
  studio.patch({ op: 'reparent', id: imageA, parentId: 'sc1' })
  assert.deepEqual(indexMap(studio), expected)
  const deep = studio.get().tree.find(row => row.name === 'DeepImage').id
  studio.patch({ op: 'remove', id: deep })
  studio = createStudio(studio.archiveData())
  const added = studio.patch({ op: 'add', kind: 'image', parentId: tree, name: 'NewImage' })
  assert.equal(added.root.children[1].children.find(node => node.name === 'NewImage').giaInfoIndex, 9, 'deleted high numbers are not reused')
  const archive = studio.archiveData()
  studio = createStudio(archive)
  const before = studio.archiveData().assets.client
  encodeStudio(studio)
  encodeStudio(studio, 'gia-combined')
  assert.deepEqual(studio.archiveData().assets.client, before, 'exports do not renumber registered assets')
})

test('legacy JSON with missing root and child numbers is registered before saving', () => {
  const seed = emptyAuthoring()
  const panel = createNode('container', { id: 'panel', name: 'Panel' })
  panel.children.push(createNode('image', { id: 'a', name: 'A' }), createNode('image', { id: 'b', name: 'B' }))
  seed.root.children.push(panel, createNode('container', { id: 'other', name: 'Other' }))
  const untouched = JSON.stringify(seed)
  const studio = createStudio(seed)
  assert.equal(JSON.stringify(seed), untouched, 'loading must not rewrite the caller input')
  assert.deepEqual(indexMap(studio), { Panel: 2, A: 3, B: 4, Other: 5 })
  assert.deepEqual(indexMap(createStudio(studio.archiveData())), indexMap(studio))
  const project = structuredClone(seed)
  exportGia(project)
  assert.equal(project.meta.giaNextAssetIndex, 6, 'direct codec callers persist the one-time allocation too')
})

test('independently observed imported template/child shared index is preserved, new assets do not alias it', () => {
  // gia_toggles official template image 1073741893 and button child image
  // 1073741936 both carry Info.index=10, so no blanket child uniqueness rule.
  const fixture = envelope(cat(
    msg(1, nativeUnit(1073741893, 'ImageTemplate', 10, 84)),
    msg(1, nativeUnit(1073741890, 'ButtonTemplate', 7, 81, [1073741936])),
    msg(2, nativeUnit(1073741936, 'ImageInstance', 10, 84, [], 1073741890)),
    str(3, '1-1-1-\\aliases.gia'), str(5, '7.0.51')))
  const studio = createStudio(importGia(fixture).project)
  const parent = studio.get().root.children[1].id
  studio.patch({ op: 'add', kind: 'image', parentId: parent, name: 'NewImage' })
  const restored = createStudio(studio.archiveData())
  const bytes = encodeStudio(restored)
  assert.deepEqual(byName(bytes), { ImageTemplate: 10, ButtonTemplate: 7, ImageInstance: 10, NewImage: 11 })
  assert.equal(validateGiaCompatibility(bytes).valid, true)
})

