import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createStudio, importGia } from '../studio/index.js'

const stem = process.argv[2] || '融合联动示例.6'
if (!/^[^/\\]+\.\d+$/.test(stem)) throw new Error('Provide a versioned example filename without a directory')
const path = extension => fileURLToPath(new URL(`../look2-workspace/${stem}.${extension}`, import.meta.url))
const bytes = readFileSync(path('save.json'))
const archive = JSON.parse(bytes)
const studio = createStudio(archive)
const before = studio.archiveData(), beforeHistory = studio.get().history
const playerPath = studio.exportData('animation-lua', 'panel').filename.replace(/\.lua$/i, '')
assert.ok(studio.get().scripts.find(row => row.path === 'fusion/controller.lua').source.includes(JSON.stringify(playerPath)), `controller must use stable player path ${playerPath}`)
const text = snapshot => snapshot.logs.map(row => row.text).join('\n')
const findAll = (roots, name) => roots.flatMap(root => [
  ...(root.name === name ? [root] : []), ...findAll(root.children || [], name),
])
const client = studio.playStart({ asset: 'client', templateRootId: 'panel', animationId: 'rise', inspect: true })
assert.equal(client.mountError, null, text(client))
assert.equal(findAll(client.tree, '融合演示容器').length, 1)
studio.playStep(.5)
assert.match(text(studio.playGet()), /fusion-event\t中点\trise/)
studio.playKey('KeyboardCraftspersonKey1Down')
let snapshot = studio.playStep(.5, { inspect: true })
let star = findAll(snapshot.tree, '动画五角星')[0]
assert.equal(star.localRotationZ, 180)
assert.equal(star.anchoredPositionY, 20, 'switch restores rise animation displacement')
studio.playStop()
assert.deepEqual(studio.archiveData(), before)
assert.deepEqual(studio.get().history, beforeHistory)
const full = studio.playStart({ asset: 'server', playerCount: 2, inspect: true })
assert.equal(full.mountError, null, text(full))
assert.equal(findAll(full.tree, '融合演示容器').length, 2)
assert.match(text(full), /fusion-instances\ttrue\ttrue/)
studio.playClick('动画切换按钮')
snapshot = studio.playStep(.5, { inspect: true })
assert.deepEqual(findAll(snapshot.tree, '动画五角星').map(row => row.localRotationZ), [180, 180])
assert.ok(snapshot.server.inbound.some(row => JSON.stringify(row).includes('Fusion_Play')))
assert.ok(snapshot.server.outbound.some(row => JSON.stringify(row).includes('Fusion_PlayAck')))
assert.ok(JSON.stringify(snapshot.server.vars).includes('LastAnimation'))
studio.playSetView(2)
snapshot = studio.playGet({ inspect: true })
assert.deepEqual(findAll(snapshot.tree, '动画五角星').map(row => row.localRotationZ), [0, 0], 'other player remains on rise')
studio.playStop()
assert.deepEqual(studio.archiveData(), before)
assert.deepEqual(studio.get().history, beforeHistory)
const restored = createStudio()
restored.importData('json', studio.exportData('save').data, 'roundtrip.save.json')
assert.equal(restored.get().look2.animations.length, 2)
assert.equal(restored.get().scripts.length, 2)
assert.equal(restored.get().serverLogic.rules.length, 1)
const imported = importGia(readFileSync(path('gia')))
assert.ok(imported.scripts.some(row => row.source.includes('Look2PlayByName')))
assert.ok(imported.scripts.some(row => row.source.includes('Fusion_PlayAck')))
assert.ok(imported.scripts.some(row => row.source.includes('fusion-instances')))
const fromGia = createStudio()
fromGia.importData('gia', readFileSync(path('gia')).toString('base64'), `${stem}.gia`)
const importedPanel = findAll([fromGia.archiveData().assets.client.root], '融合演示容器')[0]
assert.ok(importedPanel)
const giaStart = fromGia.playStart({ asset: 'client', templateRootId: importedPanel.id, inspect: true })
assert.equal(giaStart.mountError, null, text(giaStart))
fromGia.playKey('KeyboardCraftspersonKey1Down')
const giaFrame = fromGia.playStep(.5, { inspect: true })
assert.equal(findAll(giaFrame.tree, '动画五角星')[0].localRotationZ, 180)
assert.ok(!giaFrame.logs.some(row => row.level === 'error'), text(giaFrame))
fromGia.playStop()
assert.deepEqual(readFileSync(path('save.json')), bytes)
console.log(`${stem}: runtime animation switching, event handlers, player isolation, archive/history isolation, save/GIA roundtrip passed`)
